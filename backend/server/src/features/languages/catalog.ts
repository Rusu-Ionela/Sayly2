export const LANGUAGE_CATALOG: readonly LanguageCatalogEntry[] = RAW.map((language, index) => ({
  ...language,
  sortOrder: index + 1,
}));

const LANGUAGE_CODES = new Set(LANGUAGE_CATALOG.map((language) => language.code));

const LANGUAGE_ALIASES: Record<string, string> = {
  "zh-cn": "zh",
  "zh-tw": "zh",
  "pt-br": "pt",
  "en-us": "en",
  "en-gb": "en",
  iw: "he",
  in: "id",
  fil: "tl",
  nb: "no",
};

export function normalizeLanguageCode(value: string): string | null {
  const trimmed = value.trim().toLowerCase().replace(/_/g, "-");
  if (!trimmed) {
    return null;
  }

  const aliased = LANGUAGE_ALIASES[trimmed] ?? (trimmed.includes("-") ? trimmed.split("-")[0] : trimmed);
  if (!aliased || !/^[a-z]{2,3}$/.test(aliased)) {
    return null;
  }
  return LANGUAGE_CODES.has(aliased) ? aliased : null;
}
